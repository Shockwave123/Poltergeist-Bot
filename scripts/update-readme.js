/**
 * README updater (same spirit as the version updater):
 * - keeps the header version badge in sync with package.json
 * - keeps the Node.js badge in sync with engines.node
 * - regenerates the stats + full command index section between
 *   <!-- stats:start --> and <!-- stats:end --> markers
 *
 * Usage: node scripts/update-readme.js   (also: npm run readme)
 * Idempotent: running it twice reports "already up to date".
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const readmePath = path.join(root, 'Readme.md');
const pkg = require(path.join(root, 'package.json'));

const log = (message) => console.log(`[readme] ${message}`);

if (!fs.existsSync(readmePath)) {
  log('Readme.md not found - nothing to update.');
  process.exit(1);
}

let content = fs.readFileSync(readmePath, 'utf8');
const eol = content.includes('\r\n') ? '\r\n' : '\n';
const changes = [];

// 1. Version badge in the header -------------------------------------------------
const versionBadge = `[![Version](https://img.shields.io/badge/version-${pkg.version}-blue?style=for-the-badge)](package.json)`;
const versionBadgePattern = /\[!\[Version\]\(https:\/\/img\.shields\.io\/badge\/version-[^)]*\)\]\(package\.json\)/;
if (versionBadgePattern.test(content)) {
  const updated = content.replace(versionBadgePattern, versionBadge);
  if (updated !== content) changes.push(`version badge -> ${pkg.version}`);
  content = updated;
} else if (/^.*\[!\[License[^\n]*$/m.test(content)) {
  content = content.replace(/^((?:.*)\[!\[License[^\n]*)$/m, `$1${eol}${versionBadge}`);
  changes.push(`version badge added (${pkg.version})`);
}

// 2. Node.js badge follows engines.node ------------------------------------------
const nodeMajor = String(pkg.engines?.node || '').match(/\d+/)?.[0] || '20';
const beforeNode = content;
content = content.replace(/(img\.shields\.io\/badge\/Node\.js-)\d+(%2B)?/, `$1${nodeMajor}%2B`);
if (content !== beforeNode) changes.push(`Node.js badge -> ${nodeMajor}+`);

// 3. Regenerate the stats + command index section --------------------------------
let groups = [];
try {
  const { loadCommands } = require(path.join(root, 'utils', 'commandLoader'));
  const { groupCommands } = require(path.join(root, 'utils', 'commandPresentation'));
  groups = groupCommands(loadCommands());
} catch (error) {
  log(`WARNING: could not load commands (${error.message}) - stats section skipped.`);
}

if (groups.length) {
  let prefix = '.';
  try { prefix = require(path.join(root, 'config')).prefix || '.'; } catch { /* keep default */ }

  const total = groups.reduce((sum, group) => sum + group.commands.length, 0);
  const depCount = Object.keys(pkg.dependencies || {}).length;

  const lines = [
    '<!-- stats:start -->',
    '## 📊 Project Stats',
    '',
    '> Auto-generated by `node scripts/update-readme.js` — do not edit this section by hand.',
    '',
    '| | |',
    '| --- | --- |',
    `| 🤖 **Bot version** | \`${pkg.version}\` |`,
    `| ⚡ **Commands** | **${total}** across **${groups.length}** categories (prefix \`${prefix}\`) |`,
    `| 📦 **Direct dependencies** | **${depCount}** |`,
    `| 🟢 **Node.js required** | \`${pkg.engines?.node || 'n/a'}\` |`,
    '',
    '<details>',
    `<summary><b>🗂️ Full command index (${total})</b></summary>`,
    '',
  ];
  groups.forEach((group) => {
    const names = group.commands.map((command) => `\`${prefix}${command.name}\``);
    const rows = [];
    for (let index = 0; index < names.length; index += 6) rows.push(names.slice(index, index + 6).join(' · '));
    lines.push(`#### ${group.icon} ${group.label} · ${group.commands.length}`, ...rows, '');
  });
  lines.push('</details>', '<!-- stats:end -->');
  const section = lines.join(eol);

  if (content.includes('<!-- stats:start -->')) {
    const updated = content.replace(/<!-- stats:start -->[\s\S]*?<!-- stats:end -->/, () => section);
    if (updated !== content) changes.push(`stats section refreshed (${total} commands)`);
    content = updated;
  } else if (/^## 🙏 Credits\s*$/m.test(content)) {
    content = content.replace(/^(## 🙏 Credits\s*)$/m, (_, heading) => `${section}${eol}${eol}${heading}`);
    changes.push(`stats section inserted before Credits (${total} commands)`);
  } else {
    content = `${content.replace(/\s*$/, '')}${eol}${eol}${section}${eol}`;
    changes.push(`stats section appended (${total} commands)`);
  }
}

if (changes.length) {
  fs.writeFileSync(readmePath, content);
  changes.forEach((change) => log(`updated: ${change}`));
  log('Readme.md saved.');
} else {
  log('Readme.md already up to date.');
}

// Required command/config modules may keep timers open - exit explicitly.
process.exit(0);
